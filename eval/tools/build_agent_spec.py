#!/usr/bin/env python3
"""Assemble the agent's fixed text into one JavaScript module, so the evaluation and the Worker run the same agent.

Usage (from the repository root): python3 eval/tools/build_agent_spec.py
Reads:
  agent/instructions.md          the agent's instructions, written by hand
  agent/decision_schema.json     the shape of the report the model returns
  docs/EVAL_PLAN.md              the criteria, exactly as the labeling page and the third reader show them
  docs/CHARTER.md                the three outcomes, from the authority statement
  data/policy/passages.json      the policy text of L34220, split into numbered passages
  agent/routing.js, agent/record.js, agent/agent.js   only to fingerprint them
Writes agent/spec.generated.js, holding the system prompt, the schema, the passage ids, and SPEC_SHA256: one
fingerprint over the system prompt, the schema, and the three code files. Every run records it, so anyone can tell
which agent ran. The "Agent checks" workflow rebuilds this file and fails if it differs from the committed one.
"""
import hashlib, json, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from build_case_pages import LEGEND, criteria_text, outputs_text  # the same text the labelers see

OUT = "agent/spec.generated.js"
CODE = ["agent/routing.js", "agent/record.js", "agent/agent.js"]


def system_prompt(passages):
    # The labelers' legend, with "the case page" named as the agent sees it.
    assert LEGEND.count("the ids on the case page") == 1
    legend = LEGEND.replace("the ids on the case page", "ids from the list you may cite")
    instructions = open("agent/instructions.md", encoding="utf-8").read().strip().replace("{{LEGEND}}", legend)
    assert "{{" not in instructions, "unfilled marker in agent/instructions.md"
    lines = [instructions, "",
             "=== CRITERIA (from docs/EVAL_PLAN.md, Criterion inventory) ===", "", criteria_text(), "",
             "=== OUTCOMES (from docs/CHARTER.md, authority statement; the rule in code chooses among them) ===", "",
             outputs_text(), "",
             f"=== POLICY PASSAGES (LCD {passages['lcd_id']}, revision effective {passages['source_revision']}) ===", ""]
    for p in passages["passages"]:
        lines.append(f"[{p['id']}] ({p['criterion']}) {p['text']}")
    return "\n".join(lines) + "\n"


def main():
    passages = json.load(open("data/policy/passages.json", encoding="utf-8"))
    schema = json.load(open("agent/decision_schema.json", encoding="utf-8"))
    prompt = system_prompt(passages)
    h = hashlib.sha256()
    h.update(prompt.encode("utf-8"))
    h.update(json.dumps(schema, sort_keys=True).encode("utf-8"))
    files = {}
    for path in CODE:
        data = open(path, encoding="utf-8").read().encode("utf-8")
        files[path] = hashlib.sha256(data).hexdigest()
        h.update(data)
    js = "\n".join([
        "// Generated by eval/tools/build_agent_spec.py. Do not edit by hand: edit agent/instructions.md,",
        "// agent/decision_schema.json, or the criteria in docs/EVAL_PLAN.md, then run the script.",
        f"export const SPEC_SHA256 = {json.dumps(h.hexdigest())};",
        f"export const SPEC_FILES = {json.dumps(files, indent=1)};",
        f"export const POLICY = {json.dumps({'lcd_id': passages['lcd_id'], 'source_revision': passages['source_revision']})};",
        f"export const PASSAGE_IDS = {json.dumps([p['id'] for p in passages['passages']])};",
        f"export const SCHEMA = {json.dumps(schema, indent=1)};",
        f"export const SYSTEM_PROMPT = {json.dumps(prompt, ensure_ascii=False)};",
        "",
    ])
    open(OUT, "w", encoding="utf-8").write(js)
    print(f"wrote {OUT} (spec sha256 {h.hexdigest()[:12]}, system prompt {len(prompt)} characters)")


if __name__ == "__main__":
    main()
