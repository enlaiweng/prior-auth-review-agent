#!/usr/bin/env python3
"""Build the labeling site's content module from the repository.

Usage (from the repository root): python3 labeling-site/build_content.py
Run by eval/tools/rebuild_golden.sh after the labeling and practice pages, so the "Validate golden set" workflow fails if
the committed module is out of date with the cases, the criteria, the policy text, or the training.

Reads:
  data/golden/case_NN/bundle.json and data/practice/practice_*/bundle.json (through eval/tools/build_case_pages.py)
  docs/EVAL_PLAN.md (criteria), docs/CHARTER.md (outcomes), data/policy/L34220.md (policy text)
  eval/labeling/training.html (the training, served with a note at the top for invited labelers)
  labeling-site/pages/*.html (the site's own pages)
Writes:
  labeling-site/src/content.generated.js

The module holds case records and reference text only. It never holds labels of any kind, the locked intended answers,
or the practice cases' worked answers beyond what training.html already shows.
"""
import base64, glob, hashlib, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval", "tools"))
os.chdir(ROOT)
import build_case_pages as b  # noqa: E402

OUT = "labeling-site/src/content.generated.js"
PAGES = ("landing", "continue", "app", "admin")
# Shown at the top of the training for outside labelers: the training was written for the owner.
TRAINING_NOTE = (
    '<div style="background:var(--accent-weak);border-bottom:1px solid var(--accent);padding:10px 16px;font-size:14px;color:var(--fg)">'
    "<b>A note for invited labelers.</b> This training was written for the project's owner, who labels all 12 cases and later "
    "settles the disagreements between readers. As an invited labeler you label only the cases assigned to you, on the labeling "
    "site, and your answers are compared with the other readers'. You can skip Part 1 of the guide, which is about opening this "
    "page on the owner's computer. Everything about the rules, the practice cases, and the walkthrough applies to you. Practice "
    "answers stay in this browser and are not sent anywhere.</div>")


def script_hash(page, name):
    """The CSP hash of the page's one inline script ('sha256-...'), or None if it has none."""
    scripts = re.findall(r"<script>(.*?)</script>", page, flags=re.S)
    assert len(scripts) == len(re.findall(r"<script", page)) <= 1, f"{name}: one plain inline script at most"
    if not scripts:
        return None
    return "sha256-" + base64.b64encode(hashlib.sha256(scripts[0].encode("utf-8")).digest()).decode()


def case_sha(view):
    return hashlib.sha256(json.dumps(view, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def css():
    t = b.LABELING_TEMPLATE
    return t[t.index("<style>") + len("<style>"):t.index("</style>")].strip()


def main():
    cases, order = {}, []
    for d in sorted(glob.glob(b.CASE_GLOB)):
        v = b.case_view(d)
        cases[v["case"]] = {"name": v["case"].replace("case_", "Case "), "kind": "golden", "view": v, "case_sha": case_sha(v)}
        order.append(v["case"])
    for d in sorted(glob.glob("data/practice/practice_[a-z]")):
        v = b.case_view(d)
        cases[v["case"]] = {"name": "Practice " + v["case"].split("_", 1)[1].upper(), "kind": "practice", "view": v, "case_sha": case_sha(v)}
        order.append(v["case"])
    head, body = b.policy_text()
    reference = {"policy_head": head, "policy_body": body, "criteria": b.criteria_text(), "outputs": b.outputs_text(), "legend": b.LEGEND}
    # The fingerprint of what a labeler sees: saved with every label, so an exported label says which content it was made on.
    content_sha = hashlib.sha256(json.dumps({"cases": cases, "reference": reference}, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
    style = css()
    pages = {name: open(f"labeling-site/pages/{name}.html").read().replace("__CSS__", style) for name in PAGES}
    for name, page in pages.items():
        assert "__CSS__" not in page, name
    assert pages["landing"].count("__MESSAGE__") == 1
    assert pages["continue"].count("__FOR__") == 1 and pages["continue"].count("__SWITCH__") == 1
    training = open("eval/labeling/training.html").read()
    assert training.count("<body>") == 1, "training.html: one <body>"
    pages["training"] = training.replace("<body>", "<body>\n" + TRAINING_NOTE)
    hashes = {name: h for name, page in pages.items() if (h := script_hash(page, name))}
    assert set(hashes) == {"continue", "app", "admin", "training"}, sorted(hashes)
    content = {"content_sha": content_sha, "order": order, "cases": cases, **reference, "pages": pages, "script_hashes": hashes}
    with open(OUT, "w") as f:
        f.write("// Generated by labeling-site/build_content.py from the repository. Do not edit by hand.\n")
        f.write("export const CONTENT = " + json.dumps(content, ensure_ascii=False, indent=None, sort_keys=True) + ";\n")
    print(f"wrote {OUT} ({len(order)} cases, content {content_sha[:12]})")


if __name__ == "__main__":
    main()
